    def _get_javascript(self, model_names: List[str], wer_values: List[float], 
                        cer_values: List[float], inference_times: List[float]) -> str:
        """Get JavaScript for charts and interactivity."""
        return f'''
        // Chart.js configuration
        const modelNames = {json.dumps(model_names)};
        const werValues = {json.dumps(wer_values)};
        const cerValues = {json.dumps(cer_values)};
        const inferenceTimes = {json.dumps(inference_times)};
        
        // WER/CER Comparison Chart
        const ctxMetrics = document.getElementById('metricsChart').getContext('2d');
        new Chart(ctxMetrics, {{
            type: 'bar',
            data: {{
                labels: modelNames,
                datasets: [
                    {{
                        label: 'WER (%)',
                        data: werValues,
                        backgroundColor: 'rgba(37, 99, 235, 0.8)',
                        borderColor: 'rgba(37, 99, 235, 1)',
                        borderWidth: 1
                    }},
                    {{
                        label: 'CER (%)',
                        data: cerValues,
                        backgroundColor: 'rgba(22, 163, 74, 0.8)',
                        borderColor: 'rgba(22, 163, 74, 1)',
                        borderWidth: 1
                    }}
                ]
            }},
            options: {{
                responsive: true,
                maintainAspectRatio: false,
                plugins: {{
                    title: {{
                        display: true,
                        text: 'Word Error Rate & Character Error Rate'
                    }}
                }},
                scales: {{
                    y: {{
                        beginAtZero: true,
                        max: 100,
                        title: {{
                            display: true,
                            text: 'Error Rate (%)'
                        }}
                    }}
                }}
            }}
        }});
        
        // Inference Time Chart
        const ctxTime = document.getElementById('timeChart').getContext('2d');
        new Chart(ctxTime, {{
            type: 'bar',
            data: {{
                labels: modelNames,
                datasets: [{{
                    label: 'Avg. Inference Time (s)',
                    data: inferenceTimes,
                    backgroundColor: 'rgba(234, 88, 12, 0.8)',
                    borderColor: 'rgba(234, 88, 12, 1)',
                    borderWidth: 1
                }}]
            }},
            options: {{
                responsive: true,
                maintainAspectRatio: false,
                plugins: {{
                    title: {{
                        display: true,
                        text: 'Average Inference Time per File'
                    }}
                }},
                scales: {{
                    y: {{
                        beginAtZero: true,
                        title: {{
                            display: true,
                            text: 'Time (seconds)'
                        }}
                    }}
                }}
            }}
        }});
        
        // Collapsible functionality
        document.querySelectorAll('.collapsible').forEach(button => {{
            button.addEventListener('click', function() {{
                this.classList.toggle('active');
                const content = this.nextElementSibling;
                content.classList.toggle('show');
            }});
        }});
        '''
    
    def _build_summary_section(self, results: List[Dict], metadata: Optional[Dict]) -> str:
        """Build summary statistics section."""
        total_files = sum(r.get('files_processed', 0) for r in results)
        avg_files = total_files // len(results) if results else 0
        
        # Find best model
        best_wer = min(results, key=lambda x: x.get('avg_wer', float('inf')))
        best_cer = min(results, key=lambda x: x.get('avg_cer', float('inf')))
        fastest = min(results, key=lambda x: x.get('avg_inference_time', float('inf')))
        
        return f'''
        <section class="section">
            <h2 class="section-title">📊 Summary</h2>
            <div class="summary-grid">
                <div class="summary-card">
                    <h3>Models Evaluated</h3>
                    <div class="value">{len(results)}</div>
                </div>
                <div class="summary-card success">
                    <h3>Files Processed</h3>
                    <div class="value">{avg_files}</div>
                </div>
                <div class="summary-card">
                    <h3>Best WER</h3>
                    <div class="value">{best_wer.get('avg_wer', 0):.2%}</div>
                    <small>{best_wer.get('model_name', 'N/A')}</small>
                </div>
                <div class="summary-card success">
                    <h3>Best CER</h3>
                    <div class="value">{best_cer.get('avg_cer', 0):.2%}</div>
                    <small>{best_cer.get('model_name', 'N/A')}</small>
                </div>
                <div class="summary-card warning">
                    <h3>Fastest Model</h3>
                    <div class="value">{fastest.get('avg_inference_time', 0):.1f}s</div>
                    <small>{fastest.get('model_name', 'N/A')}</small>
                </div>
            </div>
        </section>
        '''
    
    def _build_charts_section(self, model_names: List[str], wer_values: List[float],
                              cer_values: List[float], inference_times: List[float]) -> str:
        """Build charts section."""
        return '''
        <section class="section">
            <h2 class="section-title">📈 Performance Charts</h2>
            <div class="charts-grid">
                <div class="chart-container">
                    <canvas id="metricsChart"></canvas>
                </div>
                <div class="chart-container">
                    <canvas id="timeChart"></canvas>
                </div>
            </div>
        </section>
        '''
    
    def _build_comparison_table(self, results: List[Dict]) -> str:
        """Build model comparison table."""
        # Find best values for highlighting
        best_wer = min(r.get('avg_wer', float('inf')) for r in results)
        best_cer = min(r.get('avg_cer', float('inf')) for r in results)
        best_time = min(r.get('avg_inference_time', float('inf')) for r in results)
        
        rows = ""
        for r in results:
            wer = r.get('avg_wer', 0)
            cer = r.get('avg_cer', 0)
            time = r.get('avg_inference_time', 0)
            
            # Determine badge class based on WER
            if wer < 0.2:
                badge_class = "badge-success"
            elif wer < 0.5:
                badge_class = "badge-warning"
            else:
                badge_class = "badge-danger"
            
            # Add best badge
            wer_badge = '<span class="best-badge">🏆 Best</span>' if wer == best_wer else ''
            cer_badge = '<span class="best-badge">🏆 Best</span>' if cer == best_cer else ''
            time_badge = '<span class="best-badge">⚡ Fastest</span>' if time == best_time else ''
            
            rows += f'''
            <tr>
                <td><strong>{html.escape(r.get('model_name', 'Unknown'))}</strong></td>
                <td>{r.get('model_id', 'N/A')}</td>
                <td>{r.get('files_processed', 0)}</td>
                <td><span class="badge {badge_class}">{wer:.2%}</span>{wer_badge}</td>
                <td>{cer:.2%}{cer_badge}</td>
                <td>{time:.2f}s{time_badge}</td>
                <td>{r.get('total_time', 0):.1f}s</td>
            </tr>
            '''
        
        return f'''
        <section class="section">
            <h2 class="section-title">📋 Model Comparison</h2>
            <table>
                <thead>
                    <tr>
                        <th>Model</th>
                        <th>Model ID</th>
                        <th>Files</th>
                        <th>Avg WER</th>
                        <th>Avg CER</th>
                        <th>Avg Time/File</th>
                        <th>Total Time</th>
                    </tr>
                </thead>
                <tbody>
                    {rows}
                </tbody>
            </table>
        </section>
        '''
    
    def _build_detailed_results(self, results: List[Dict]) -> str:
        """Build detailed per-file results with collapsible sections."""
        sections = ""
        
        for r in results:
            model_name = r.get('model_name', 'Unknown')
            per_file = r.get('per_file_results', [])
            
            if not per_file:
                continue
            
            # Build per-file items
            items = ""
            for pf in per_file[:50]:  # Limit to 50 files for performance
                wer = pf.get('wer', 0)
                cer = pf.get('cer', 0)
                
                # Determine error class
                if wer < 0.2:
                    error_class = "error-low"
                elif wer < 0.5:
                    error_class = "error-medium"
                else:
                    error_class = "error-high"
                
                gt_text = html.escape(pf.get('ground_truth', ''))
                pred_text = html.escape(pf.get('prediction', ''))
                
                items += f'''
                <div class="prediction-item {error_class}">
                    <strong>{html.escape(pf.get('audio_file', 'Unknown'))}</strong>
                    <div class="prediction-metrics">
                        <span class="metric"><span class="metric-label">WER:</span> {wer:.2%}</span>
                        <span class="metric"><span class="metric-label">CER:</span> {cer:.2%}</span>
                        <span class="metric"><span class="metric-label">Time:</span> {pf.get('inference_time', 0):.2f}s</span>
                    </div>
                    <div style="margin-top: 0.75rem;">
                        <div class="prediction-label">Ground Truth:</div>
                        <div class="prediction-text">{gt_text}</div>
                    </div>
                    <div style="margin-top: 0.5rem;">
                        <div class="prediction-label">Prediction:</div>
                        <div class="prediction-text">{pred_text}</div>
                    </div>
                </div>
                '''
            
            more_text = f'<p style="color: var(--text-muted); margin-top: 1rem;">... and {len(per_file) - 50} more files</p>' if len(per_file) > 50 else ''
            
            sections += f'''
            <button class="collapsible">
                <span>📁 {html.escape(model_name)} - {len(per_file)} files</span>
            </button>
            <div class="collapsible-content">
                {items}
                {more_text}
            </div>
            '''
        
        return f'''
        <section class="section">
            <h2 class="section-title">🔍 Detailed Results (Click to Expand)</h2>
            {sections}
        </section>
        '''
