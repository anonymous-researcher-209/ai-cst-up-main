"""
HTML Report Generator for ASR Model Comparison.

Generates interactive HTML reports with:
- Summary charts and metrics
- Expandable sections for detailed predictions
- Model-by-model comparison
- Per-file results with error highlighting
"""

import os
import json
from datetime import datetime
from typing import List, Dict, Optional
import html


class HTMLReportGenerator:
    """Generates interactive HTML reports for ASR evaluation results."""
    
    def __init__(self, output_dir: str):
        """
        Initialize HTML report generator.
        
        Args:
            output_dir: Directory to save reports
        """
        self.output_dir = output_dir
        os.makedirs(output_dir, exist_ok=True)
    
    def generate(self, results: List[Dict], metadata: Optional[Dict] = None) -> str:
        """
        Generate HTML report from evaluation results.
        
        Args:
            results: List of model evaluation results
            metadata: Optional metadata about the evaluation
            
        Returns:
            Path to generated HTML file
        """
        valid_results = [r for r in results if r is not None]
        
        if not valid_results:
            return None
        
        html_content = self._build_html(valid_results, metadata)
        
        output_path = os.path.join(self.output_dir, "report.html")
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(html_content)
        
        return output_path
    
    def _build_html(self, results: List[Dict], metadata: Optional[Dict]) -> str:
        """Build complete HTML document."""
        
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        
        # Prepare chart data
        model_names = [r.get('model_name', 'Unknown') for r in results]
        wer_values = [r.get('avg_wer', 0) * 100 for r in results]  # Convert to percentage
        cer_values = [r.get('avg_cer', 0) * 100 for r in results]
        inference_times = [r.get('avg_inference_time', 0) for r in results]
        
        return f'''<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>ASR Model Comparison Report</title>
    <script src="https://cdn.jsdelivr.net/npm/chart.js"></script>
    <style>
        {self._get_css()}
    </style>
</head>
<body>
    <div class="container">
        <header>
            <h1>🎤 ASR Model Comparison Report</h1>
            <p class="timestamp">Generated: {timestamp}</p>
        </header>
        
        {self._build_summary_section(results, metadata)}
        
        {self._build_charts_section(model_names, wer_values, cer_values, inference_times)}
        
        {self._build_comparison_table(results)}
        
        {self._build_detailed_results(results)}
        
        <footer>
            <p>Generated by ASR Evaluation Framework</p>
        </footer>
    </div>
    
    <script>
        {self._get_javascript(model_names, wer_values, cer_values, inference_times)}
    </script>
</body>
</html>'''
    
